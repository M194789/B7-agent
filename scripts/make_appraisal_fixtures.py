KAI = ImageFont.truetype('C:/Windows/Fonts/simkai.ttf', 34)
HEI = ImageFont.truetype('C:/Windows/Fonts/simhei.ttf', 60)
SMALL = ImageFont.truetype('C:/Windows/Fonts/simkai.ttf', 28)


def certificate(name, lines, issuer, date):
    image = Image.new('RGB', (1200, 850), (253, 248, 236))
    draw = ImageDraw.Draw(image)
    draw.rectangle([20, 20, 1180, 830], outline=(170, 30, 30), width=10)
    draw.rectangle([42, 42, 1158, 808], outline=(200, 160, 80), width=3)
    draw.text((600, 120), '荣 誉 证 书', font=HEI, fill=(170, 30, 30), anchor='mm')
    y = 240
    for line in lines:
        draw.text((130, y), line, font=KAI, fill=(40, 30, 30))
        y += 62
    draw.text((1070, 690), issuer, font=SMALL, fill=(40, 30, 30), anchor='rm')
    draw.text((1070, 740), date, font=SMALL, fill=(40, 30, 30), anchor='rm')
    draw.ellipse([880, 600, 1060, 780], outline=(200, 40, 40), width=5)
    draw.text((970, 690), '（印）', font=SMALL, fill=(200, 40, 40), anchor='mm')
    image.save(OUT / name, optimize=True)


